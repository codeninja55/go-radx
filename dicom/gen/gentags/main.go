// vrConst maps a DICOM VR string (PS3.6) to its dicom package VR constant name.
// The four ambiguous "X or Y" forms map to the ambiguous placeholders; the FFFE
// item VRs (Innolitics "See Note 2") and anything unmapped fall back to VRUN.
var vrConst = map[string]string{
	"AE": "VRAE", "AS": "VRAS", "AT": "VRAT", "CS": "VRCS", "DA": "VRDA",
	"DS": "VRDS", "DT": "VRDT", "FL": "VRFL", "FD": "VRFD", "IS": "VRIS",
	"LO": "VRLO", "LT": "VRLT", "OB": "VROB", "OD": "VROD", "OF": "VROF",
	"OL": "VROL", "OV": "VROV", "OW": "VROW", "PN": "VRPN", "SH": "VRSH",
	"SL": "VRSL", "SQ": "VRSQ", "SS": "VRSS", "ST": "VRST", "SV": "VRSV",
	"TM": "VRTM", "UC": "VRUC", "UI": "VRUI", "UL": "VRUL", "UN": "VRUN",
	"UR": "VRUR", "US": "VRUS", "UT": "VRUT", "UV": "VRUV",
	"US or SS":       "VRUSorSS",
	"US or OW":       "VRUSorOW",
	"OB or OW":       "VROBorOW",
	"US or SS or OW": "VRUSorSSorOW",
}

func goVR(vr string) string {
	if c, ok := vrConst[vr]; ok {
		return c
	}
	return "VRUN"
}

// attribute is one Innolitics attributes.json record.
type attribute struct {
	Tag     string `json:"tag"`
	Name    string `json:"name"`
	Keyword string `json:"keyword"`
	VR      string `json:"valueRepresentation"`
	VM      string `json:"valueMultiplicity"`
	Retired string `json:"retired"`
	ID      string `json:"id"`
}

// tagEntry is a resolved attribute ready to emit.
type tagEntry struct {
	keyword string
	vr      string // dicom VR constant name
	vm      string
	name    string

	repeating   bool
	exact       uint32 // for non-repeating: the (group<<16)|element value
	mask, value uint32 // for repeating: (tag & mask) == value matches
}

func main() {
	attrs, err := fetchAttributes()
	if err != nil {
		log.Fatalf("gentags: fetch attributes: %v", err)
	}
	entries := resolveEntries(attrs)

	uids, err := fetchUIDNames()
	if err != nil {
		log.Fatalf("gentags: fetch UID dictionary: %v", err)
	}

	if err := writeFile("tag_values.go", renderTags(entries)); err != nil {
		log.Fatalf("gentags: write tag_values.go: %v", err)
	}
	if err := writeFile("uid_values.go", renderUIDs(uids)); err != nil {
		log.Fatalf("gentags: write uid_values.go: %v", err)
	}
	log.Printf("gentags: wrote %d tag entries and %d UID names", len(entries), len(uids))
}

func fetchAttributes() ([]attribute, error) {
	body, err := get(attributesURL)
	if err != nil {
		return nil, err
	}
	var attrs []attribute
	if err := json.Unmarshal(body, &attrs); err != nil {
		return nil, err
	}
	return attrs, nil
}

// resolveEntries converts Innolitics attributes into emit-ready tagEntry values,
// dropping keyword-less rows and splitting repeating-group attributes (an "x" in the
// id) from exact ones.
func resolveEntries(attrs []attribute) []tagEntry {
	out := make([]tagEntry, 0, len(attrs))
	for _, a := range attrs {
		if a.Keyword == "" {
			continue
		}
		id := strings.ToLower(a.ID)
		if len(id) != 8 {
			continue
		}
		group := id[:4]
		vr := goVR(a.VR)
		// FFFE item tags carry no real VR; force Unknown (prototype used "NA").
		if group == "fffe" {
			vr = "VRUN"
		}
		e := tagEntry{keyword: a.Keyword, vr: vr, vm: a.VM, name: a.Name}
		if strings.Contains(id, "x") {
			mask, value, err := maskValue(id)
			if err != nil {
				log.Fatalf("gentags: %s (%s): %v", a.Keyword, a.ID, err)
			}
			e.repeating = true
			e.mask, e.value = mask, value
		} else {
			v, err := strconv.ParseUint(id, 16, 32)
			if err != nil {
				log.Fatalf("gentags: %s (%s): %v", a.Keyword, a.ID, err)
			}
			e.exact = uint32(v)
		}
		out = append(out, e)
	}
	return out
}

// maskValue derives the mask and value for a repeating-group id. Each fixed hex
// nibble contributes 0xF to the mask and its digit to the value; each "x" nibble
// contributes 0x0 to the mask and 0x0 to the value, so (tag & mask) == value matches
// any value of the variable nibbles. Closes Codex DCM-012.
func maskValue(id string) (mask, value uint32, err error) {
	for i := 0; i < len(id); i++ {
		mask <<= 4
		value <<= 4
		c := id[i]
		if c == 'x' || c == 'X' {
			continue // mask nibble 0x0, value nibble 0x0
		}
		d, e := strconv.ParseUint(string(c), 16, 8)
		if e != nil {
			return 0, 0, fmt.Errorf("non-hex nibble %q", string(c))
		}
		mask |= 0xF
		value |= uint32(d)
	}
	return mask, value, nil
}

func renderTags(entries []tagEntry) []byte {
	// Stable output: constants and tagDict by ascending tag value; repeatingDict by
	// mask then value.
	exact := make([]tagEntry, 0, len(entries))
	repeating := make([]tagEntry, 0)
	for _, e := range entries {
		if e.repeating {
			repeating = append(repeating, e)
		} else {
			exact = append(exact, e)
		}
	}
	sort.Slice(exact, func(i, j int) bool { return exact[i].exact < exact[j].exact })
	sort.Slice(repeating, func(i, j int) bool {
		if repeating[i].value != repeating[j].value {
			return repeating[i].value < repeating[j].value
		}
		return repeating[i].mask < repeating[j].mask
	})

	var b bytes.Buffer
	fmt.Fprintf(&b, "%s\n\npackage dicom\n\n", licenseHeader)
	fmt.Fprintf(&b, "// Generated %s from Innolitics dicom-standard %s.\n\n",
		time.Now().UTC().Format("2006-01-02"), innoliticsRev[:8])

	b.WriteString("// Standard DICOM tag constants (PS3.6 data dictionary).\n")
	b.WriteString("const (\n")
	for _, e := range exact {
		fmt.Fprintf(&b, "\tTag%s Tag = 0x%08X\n", e.keyword, e.exact)
	}
	b.WriteString(")\n\n")

	b.WriteString("// tagDict resolves exact-match tags to their dictionary entry.\n")
	b.WriteString("var tagDict = map[Tag]TagInfo{\n")
	for _, e := range exact {
		fmt.Fprintf(&b, "\tTag%s: {Keyword: %q, VR: %s, VM: %q, Name: %q},\n",
			e.keyword, e.keyword, e.vr, e.vm, e.name)
	}
	b.WriteString("}\n\n")

	b.WriteString("// repeatingDict resolves repeating-group tags (60xx/50xx/5xxx and\n")
	b.WriteString("// similar) by mask so an overlay tag such as (6002,3000) resolves\n")
	b.WriteString("// instead of degrading to Unknown (Codex DCM-012).\n")
	b.WriteString("var repeatingDict = []repeatingEntry{\n")
	for _, e := range repeating {
		fmt.Fprintf(&b, "\t{mask: 0x%08X, value: 0x%08X, info: TagInfo{Keyword: %q, VR: %s, VM: %q, Name: %q}},\n",
			e.mask, e.value, e.keyword, e.vr, e.vm, e.name)
	}
	b.WriteString("}\n")
	return b.Bytes()
}

// docbook table parsing (PS3.6 UID registry) -------------------------------------
//
// The DICOM PS3.6 XML is a DocBook document in the http://docbook.org/ns/docbook
// namespace. The structs below mirror table > tbody > tr > td > para; a cell's text
// is the full inner text of its first para (direct char data plus any nested
// emphasis), which covers both the plain data rows and emphasised header rows.

type dbTable struct {
	Caption string   `xml:"caption"`
	Bodies  []dbBody `xml:"tbody"`
}

type dbBody struct {
	Rows []dbRow `xml:"tr"`
}

type dbRow struct {
	Cells []dbCell `xml:"td"`
}

type dbCell struct {
	Paras []dbPara `xml:"para"`
}

type dbPara struct {
	// Inner captures all descendant character data of the para, including text held
	// inside a nested <emphasis>.
	Inner string `xml:",innerxml"`
}

type uidName struct {
	uid, name string
}

func fetchUIDNames() ([]uidName, error) {
	body, err := get(part06URL)
	if err != nil {
		return nil, err
	}
	// The PS3.6 tables are deeply nested in the DocBook document, so walk the token
	// stream and decode each <table> element wherever it appears.
	dec := xml.NewDecoder(bytes.NewReader(body))
	seen := make(map[string]bool)
	var out []uidName
	for {
		tok, err := dec.Token()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, err
		}
		se, ok := tok.(xml.StartElement)
		if !ok || se.Name.Local != "table" {
			continue
		}
		var tbl dbTable
		if err := dec.DecodeElement(&tbl, &se); err != nil {
			continue
		}
		if tbl.Caption != "UID Values" && tbl.Caption != "Well-known Frames of Reference" {
			continue
		}
		for _, b := range tbl.Bodies {
			for _, r := range b.Rows {
				if len(r.Cells) < 2 {
					continue
				}
				uid := cleanCell(cellText(r.Cells[0]))
				name := normaliseUIDName(cleanCell(cellText(r.Cells[1])))
				// Skip header rows and any row whose first column is not a UID.
				if uid == "" || name == "" || !isUID(uid) || seen[uid] {
					continue
				}
				seen[uid] = true
				out = append(out, uidName{uid: uid, name: name})
			}
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no UID registry rows parsed")
	}
	sort.Slice(out, func(i, j int) bool { return out[i].uid < out[j].uid })
	return out, nil
}

// cellText returns the concatenated text of a cell's first para, stripping any
// nested XML tags (such as <emphasis>) while keeping their text.
func cellText(c dbCell) string {
	if len(c.Paras) == 0 {
		return ""
	}
	return stripTags(c.Paras[0].Inner)
}

// stripTags removes XML element tags from s, leaving only character data, and unescapes
// the common XML entities the DICOM tables use.
func stripTags(s string) string {
	var b strings.Builder
	depth := 0
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case '<':
			depth++
		case '>':
			if depth > 0 {
				depth--
			}
		default:
			if depth == 0 {
				b.WriteByte(s[i])
			}
		}
	}
	out := b.String()
	out = strings.ReplaceAll(out, "&amp;", "&")
	out = strings.ReplaceAll(out, "&lt;", "<")
	out = strings.ReplaceAll(out, "&gt;", ">")
	out = strings.ReplaceAll(out, "&#x200b;", "")
	return out
}

// isUID reports whether s looks like a dotted-numeric OID (used to skip header rows).
func isUID(s string) bool {
	if s == "" || (s[0] < '0' || s[0] > '9') {
		return false
	}
	return strings.Contains(s, ".")
}

// cleanCell trims whitespace and removes the zero-width spaces and soft hyphens the
// DICOM XML embeds in long UID strings.
func cleanCell(s string) string {
	s = strings.ReplaceAll(s, "\u200b", "") // zero-width space
	s = strings.ReplaceAll(s, "\u00ad", "") // soft hyphen
	return strings.TrimSpace(s)
}

// normaliseUIDName mirrors the prototype's post-processing: drop a "(Retired)" marker
// and keep only the name before any ":" (the text after the colon is supplementary
// info, not part of the registered name).
func normaliseUIDName(name string) string {
	name = strings.ReplaceAll(name, "(Retired)", "")
	if i := strings.Index(name, ":"); i >= 0 {
		name = name[:i]
	}
	name = strings.ReplaceAll(name, "&", "and")
	return strings.TrimSpace(name)
}

func renderUIDs(uids []uidName) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "%s\n\npackage dicom\n\n", licenseHeader)
	fmt.Fprintf(&b, "// Generated %s from DICOM PS3.6 Tables A-1 and A-2.\n\n",
		time.Now().UTC().Format("2006-01-02"))
	b.WriteString("// uidNames maps registered DICOM UIDs to their PS3.6 name.\n")
	b.WriteString("var uidNames = map[UID]string{\n")
	for _, u := range uids {
		fmt.Fprintf(&b, "\t%q: %q,\n", u.uid, u.name)
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func writeFile(name string, src []byte) error {
	formatted, err := format.Source(src)
	if err != nil {
		// Write the unformatted source so the failure can be diagnosed.
		_ = os.WriteFile(name+".broken", src, 0o644)
		return fmt.Errorf("gofmt: %w (wrote %s.broken)", err, name)
	}
	return os.WriteFile(name, formatted, 0o644)
}

func get(url string) ([]byte, error) {
	client := &http.Client{Timeout: 5 * time.Minute}
	resp, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}
