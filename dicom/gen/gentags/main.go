const attributesURL = "https://raw.githubusercontent.com/innolitics/dicom-standard/" +
	innoliticsRev + "/standard/attributes.json"

// part06URL is the canonical DICOM PS3.6 XML data dictionary (current = 2024b at the
// pinned Innolitics revision), the source for the UID registry tables A-1 and A-2.
const part06URL = "https://dicom.nema.org/medical/dicom/current/source/docbook/part06/part06.xml"

