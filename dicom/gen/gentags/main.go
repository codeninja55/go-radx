// Command gentags regenerates the go-radx DICOM data dictionary:
//
//   - dicom/tag_values.go  — Tag* constants, the exact-match tagDict, and the
//     repeatingDict slice (60xx/50xx/5xxx-style masked entries).
//   - dicom/uid_values.go  — the uidNames map (transfer syntaxes, SOP classes,
//     well-known instances and frames of reference).
//
// Tag data is read from the Innolitics JSON representation of the DICOM standard,
// pinned to revision 7f4749d09ed3ef2fa70637d376d423a4b13523cd (rev2024b), so the
// output is reproducible. UID names are read from the canonical DICOM PS3.6 XML
// data dictionary (Tables A-1 and A-2), mirroring pydicom's generate_uid_dict.
//
// This generator ports dicom/tag/generate_tag_values.py from the prototype with two
// fixes (Codex DCM-012): repeating-group attributes (an "x" in the Innolitics tag id)
// are emitted as masked repeatingDict entries instead of collapsing "x" to "0", and a
// Tag is a uint32 rather than a struct.
//
// Run via: go generate ./dicom/...
package main

